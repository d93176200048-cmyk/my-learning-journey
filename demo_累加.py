# 演示：等号右边读的是「此刻盒子里的旧值」，等号左边写的是「新值」
# 场景：存钱罐里本来有 100 元，之后又存了 50 元、又存了 30 元

# 第 1 步：盒子先准备好，装一个数
存款 = 100
print("开始的时候，罐子里有：", 存款)

# 第 2 步：把这一次的数加进去
# 关键：等号右边那个「存款」，读的是「此刻罐子里还剩多少」
存款 = 存款 + 50
print("存了 50 之后，罐子里有：", 存款)

# 第 3 步：再来一次，同一个套路
存款 = 存款 + 30
print("再存 30 之后，罐子里有：", 存款)

