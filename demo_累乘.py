# 演示：累乘（把一个数乘进结果盒）
# 例题：输入 N，计算 2 的 N 次方（2×2×2…共 N 个 2）
# 注意：这里乘的是 2。阶乘那题你自己推 —— 结构一模一样，只改「乘谁」。

# 第 1 条：拿用户输入（第二行必须有 =，否则结果被扔掉）
N = input("请输入 N：")
N = int(N)

# 第 3 条：乘法盒子在循环外面先准备好，初始值是 1（不是 0）
结果 = 1

# 第 2 条：range 右端不含，所以 1 到 N 要写 N+1
for 数 in range(1, N+1):
    结果 = 结果 * 2

# 最后这行 print 在循环外面，循环全跑完才执行一次
print(结果)
