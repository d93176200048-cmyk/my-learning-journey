# demo_哈希.py —— 样板，给你看的，不是作业
# 哈希（hash）是什么：把一段文字，变成一串固定长度的"数字指纹"
# 用途：区块链靠它判断"数据有没有被人偷偷改过"

import hashlib  # 引入 Python 自带的"哈希工具箱"（hashlib 读作 hash-lib）

# 1. 准备一段文字
文字 = "你好，区块链"

# 2. 把文字变成字节（哈希算法只吃"字节"，不吃普通文字）
字节 = 文字.encode("utf-8")

# 3. 用 sha256 算法算哈希，再变成一串十六进制字符
指纹 = hashlib.sha256(字节).hexdigest()

# 4. 打印出来看
print("原文：", 文字)
print("哈希：", 指纹)

# 5. 改一个字，再算一次，看看变成什么样
文字2 = "你好，区块琏"  # 把"链"改成"琏"（一个字不同）
指纹2 = hashlib.sha256(文字2.encode("utf-8")).hexdigest()
print("改一字后：", 文字2)
print("新哈希：", 指纹2)
print("两个哈希一样吗？", 指纹 == 指纹2)
