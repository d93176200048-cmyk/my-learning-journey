# Day 8 演示：列表加工——塞东西、换东西、扔东西
# 这份不是练习，是给你看样子的。读一遍，跑一遍，改一处，再跑。
# ============================================

数量 = [10, 20, 30]

# 第 1 招：append（读"额喷德"）= 在最后塞一个进去
数量.append(40)
print(数量)

# 第 2 招：按编号换东西——昨天学的取件写法，反过来用
数量[0] = 99
print(数量)

# 第 3 招：remove（读"瑞慕芙"）= 扔掉指定的那个值
数量.remove(99)
print(数量)

# 命门：append 和 remove 用完，柜子已经变了，它们不递回东西
# 所以直接喊就行，不用 = 接——和「打招呼」是同一类（干活型）
