# 演示：函数会「交出结果」，= 是接住它的盒子
# 这份文件不是你的练习，是给你看样子的。

# 第 1 行：input() 问一句话，然后把「你打的字」交出来
答案 = input("随便打几个字：")
# 第 2 行：print() 把盒子里的东西显示出来
print("你打的是：", 答案)

# 第 3 行：int() 把盒子里的字变成一个真的数字，再交给另一个盒子
数字 = int(答案)
print("变成数字是：", 数字)

# 第 4 行：现在它是真的数字了，所以可以做算术
print("乘以 3 是：", 数字 * 3)
print("加 10 是：", 数字 + 10)
