# ============================================
# 演示：函数就是「给一段代码起个名字」
# 这份不是你的练习，是给你看样子的。读一遍，跑一遍，改一个数，再跑。
# ============================================

# 你一定早就见过函数了，只是不知道它叫这个名：
#
#   print("你好")    → 喊"print"，递给它一句话，它负责显示到屏幕
#   int("5")        → 喊"int"，递给它文字，它递回数字 5
#   input("问话")   → 喊"input"，递给它一句提示，它递回你打的字
#
# 它们长得都一样：   名字(递过去的东西)
#
# 今天只学一件事：自己起一个这样的名字。


# --------------------------------------------
# 第一步：定义（把配方写在本子上）
# --------------------------------------------
# def 就是「定义」（define，读"弟犯因"），意思是"我要起一个新名字了"
# 平方 = 这个新名字
# 括号里的 数字 = 你递过去的东西，在配方里就叫这个名字
def 平方(数字):

    # 函数体：递过来的那个数字，自己乘自己
    结果 = 数字 * 数字

    # return = 「递回去」（读"瑞turn"）
    # 把算出来的结果递还给调用的人
    return 结果


# --------------------------------------------
# 第二步：调用（喊名字、递东西、接结果）
# --------------------------------------------
# 平方(5) = 喊"平方"这个名字，把 5 递进去
# 等号左边 = 伸手接住它递回来的东西
答案 = 平方(5)


# --------------------------------------------
# 第三步：看看接住了什么
# --------------------------------------------
print("5 的平方是：", 答案)


# --------------------------------------------
# 注意：上面只是"定义"，光写 def 那一块，什么都不会发生。
# 真正让它动起来的，是 答案 = 平方(5) 这一行——不喊名字，它一动不动。
