# 定义一个函数，名字叫「打招呼」
# 括号里那个 递进来的名字 = 你喊它时交给它的东西（一个占位）
def 打招呼(递进来的名字):

    # 函数体：把"你好，"和递进来的那个东西一起打印
    # 注意：这里喊的是「递进来的名字」这个名字，不是写死的"陈涵"
    print("你好，", 递进来的名字)


# --------------------------------------------
# 喊它两次，递不同的东西进去
# --------------------------------------------
# 关键：一定要带括号！括号里递什么，函数里就用什么
打招呼("陈涵")
打招呼("AI")

