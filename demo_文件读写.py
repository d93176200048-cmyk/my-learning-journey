# ===== demo_文件读写.py =====
# 我写的样板：给你看的，不是作业。作业是另外三道题，在 day11_文件读写.py 里写。

# 类比：变量像便利贴（贴在内存里，程序一关就没了）；
#       文件像笔记本（写在硬盘上，关机了也还在，下次打开还能看）。

# ---------- 第一部分：写文件 ----------
# open("我的笔记.txt", "w")：打开（没有就新建）一个文件
# "w" = write，写模式。注意：如果文件原来有内容，"w" 会先把原来的全部清空！
笔记本 = open("我的笔记.txt", "w")
笔记本.write("第一行：今天学了文件读写\n")   # \n = 换行，让接下来的字另起一行
笔记本.write("第二行：数据能存在硬盘上了\n")
笔记本.close()   # close 关上文件；不关的话，内容可能没真正存进去

# ---------- 第二部分：读文件 ----------
# "r" = read，读模式：把文件里已经有的内容拿出来
笔记本 = open("我的笔记.txt", "r")
内容 = 笔记本.read()   # read() 一次把整个文件的内容读成一个字符串
笔记本.close()
print(内容)
