# 教学样板（阅读用，不是你的练习答案）
# 字典 = 用"名字"（键 key）找"值"（value）的盒子集合
# 和列表不同：列表按编号（0,1,2）取，字典按你自己起的"名字"取

商品 = {"名称": "奶茶", "价格": 15, "库存": 100}

print(商品["名称"])     # 用名字取 → 奶茶
print(商品["价格"])     # → 15

商品["价格"] = 18       # 改：把价格改成 18
商品["折扣"] = 0.9      # 加：新增一个键值对

print(商品)             # 看整个字典的变化：价格变 18，多了折扣 0.9

