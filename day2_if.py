# 第 2 课：让程序会做判断（if 条件判断）

# ============================================
# 第一部分：最简单的 if —— 如果…就…否则…
# ============================================
# if 的意思就是大白话的「如果」。
# 冒号（:）下面缩进的那几行，就是「条件成立时才做的事」。

score = 75                    # 变量 score 存了 75 分

if score >= 60:               # >= 是「大于等于」
    print("75 分：及格了")     # 注意这一行开头空了 4 格，这叫「缩进」
else:                         # else 是「否则」，上面条件不成立时走这里
    print("75 分：不及格")

# ============================================
# 第二部分：同样的代码，变量一改，结果就变了
# ============================================
# 这就是把第 1 课的「变量」和今天的「判断」接起来的效果：
# 程序不变，数据变，结论跟着变。

score = 45                    # 同一个变量，重新赋值

if score >= 60:
    print("45 分：及格了")
else:
    print("45 分：不及格")

# ============================================
# 第三部分：多个分支用 elif
# ============================================
# elif 是 else + if 的缩写，意思是「不然的话，如果……」
# 可以接很多个；Python 从上往下检查，命中第一个就停。

score = 88

if score >= 90:
    print("88 分：优秀")
elif score >= 80:
    print("88 分：良好")
elif score >= 60:
    print("88 分：及格")
else:
    print("88 分：不及格")

# ============================================
# 第四部分：两个条件同时判断（and / or）
# ============================================
age = 20
has_money = True              # True 是「真」，False 是「假」，首字母必须大写

if age >= 18 and has_money:   # and 表示两个条件都要成立
    print("20 岁且有钱：可以买")

age = 16
if age >= 18 or has_money:    # or 表示满足任意一个就行
    print("16 岁但有钱：也放行")

# ============================================
# 小结（这节课真正学到的四件事）：
# 1. if / elif / else 就是「如果 / 不然如果 / 否则」
# 2. 判断符号：>  <  ==  !=  >=  <=
# 3. 冒号下面缩进 4 格的代码，才属于这个 if 内部
# 4. and 是「都要满足」，or 是「满足一个就够」
