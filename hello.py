# 说明：以井号（#）开头的行叫「注释」，电脑会直接跳过不执行，
# 注释是写给人看的笔记，用来解释这行代码在干什么。

# --------------------------------------------
# 第一部分：print —— 让电脑把内容显示到屏幕上
# --------------------------------------------
# print 的英文原意是"打印"，在编程里的作用是"输出到屏幕"。
# 括号里用引号括起来的叫「字符串」（一串文字）。
print("Hello, Web3!")            # 屏幕上会出现：Hello, Web3!
print("我开始学 Python 了")       # 引号里写中文也能正常显示

# --------------------------------------------
# 第二部分：Python 是个计算器
# --------------------------------------------
# 加减乘除的符号：+ 加  - 减  * 乘  / 除
# 电脑算数比你快，也比你自己按计算器不容易错。
print(1 + 1)                     # 输出 2
print(2026 - 1998)               # 输出 28
print(12 * 8)                    # 输出 96
print(100 / 4)                   # 输出 25.0（除法结果带小数点）

# --------------------------------------------
# 第三部分：变量 —— 给数据贴一个标签
# --------------------------------------------
# 变量的作用像便利贴：把数据存起来，在旁边贴上名字，
# 以后喊这个名字，就能把数据取出来用。
age = 18                         # 等号（=）是"赋值"：把 18 存进 age 这个标签
print(age)                       # 输出 18

age = age + 1                    # 右边先算（18+1=19），再把 19 存回 age
print(age)                       # 输出 19

# --------------------------------------------
# 第四部分：把文字和变量拼在一起输出
# --------------------------------------------
# 逗号在 print 里表示"分段输出，段与段之间自动加一个空格"
name = "学习者"
print("我的名字是", name, "，明年", age, "岁")

# --------------------------------------------
# 小结（今天真正学到的三件事）：
# 1. print() 负责输出，井号开头是注释
# 2. Python 可以直接当计算器用
# 3. 变量用等号赋值，可以反复重新赋值
