# 教学样板（阅读用，不是你的练习答案）
# 切片 = 一次从列表里取"连续好几格"，不用一格一格取

气温 = [20, 22, 25, 23, 19, 18, 21]   # 周一到周日的气温

# 写法：列表[起点编号 : 终点编号]
# 注意：右端那个编号"不含"——和 range 一个毛病
print(气温[1:4])     # 取周二到周四 → [22, 25, 23]（终点 4 不含，所以到编号 3 为止）
print(气温[:3])      # 起点不写 = 从头取；前三天 → [20, 22, 25]
print(气温[4:])      # 终点不写 = 取到末尾；周五到周日 → [19, 18, 21]
print(气温[-2:])     # 用负数：最后两天 → [18, 21]

# 切片有个温柔的地方：就算编号越界也不报错
print(气温[5:99])    # 不会崩，能取多少取多少 → [18, 21]
